/** ตัดวงเล็บรหัสท้ายชื่อออก เช่น "อุจจาระร่วง [02]" → "อุจจาระร่วง" */
export function cleanDiseaseName(raw: string): string {
  return (raw ?? "").replace(/\s*\[\d+\]\s*$/, "").trim();
}

/** ชื่อโรคจากรหัส 506 — คืน "รหัส <code>" ถ้าไม่มีในบัญชี */
export function disease506Name(code: string): string {
  const c = (code ?? "").trim();
  if (!c) return "ไม่ระบุ";
  // รองรับทั้ง "2" และ "02"
  return CODE506_NAMES[c] ?? CODE506_NAMES[c.padStart(2, "0")] ?? `รหัส ${c}`;
}
